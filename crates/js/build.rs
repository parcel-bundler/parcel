use std::env;
use std::fs;
use std::path::PathBuf;

use swc_core::common::{
  FileName, GLOBALS, Globals, Mark, SourceMap, comments::SingleThreadedComments, errors::HANDLER,
  sync::Lrc,
};
use swc_core::ecma::ast::{Decl, EsVersion, Module, ModuleItem, Program, Stmt};
use swc_core::ecma::codegen::{
  Config, Emitter,
  text_writer::{JsWriter, WriteJs, omit_trailing_semi},
};
use swc_core::ecma::minifier::optimize;
use swc_core::ecma::minifier::option::{
  CompressOptions, ExtraOptions, MangleOptions, MinifyOptions,
};
use swc_core::ecma::parser::{EsSyntax, Parser, StringInput, Syntax, lexer::Lexer};
use swc_core::ecma::transforms::base::{fixer::fixer, resolver};
use swc_core::ecma::visit::{Visit, VisitMut, VisitMutWith, VisitWith};

const RUNTIME_GLOBALS: &[(&str, &str)] = &[
  ("modules", "m"),
  ("parcelRequireName", "p"),
  ("externals", "x"),
  ("manifest", "k"),
  ("entries", "e"),
  ("mainEntry", "n"),
  ("awaitedBundles", "b"),
  ("require", "r"),
  ("distDir", "d"),
  ("publicUrl", "u"),
  ("bundleUrl", "l"),
  ("$parcel$path", "v"),
  ("$parcel$bundleDir", "w"),
  // The ESM helpers' functions (see `ESM_HELPER_FUNCTIONS` in src/runtime_modules.rs).
  ("$parcel$export", "t"),
  ("$parcel$exportAll", "a"),
  ("$parcel$interopDefault", "i"),
  ("$parcel$defineInteropFlag", "f"),
];

fn main() {
  println!("cargo:rerun-if-changed=build.rs");
  let out_dir = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is not set"));
  for name in ["runtime", "tla-runtime"] {
    let source = read_sources(&[name]);
    fs::write(
      out_dir.join(format!("{name}.min.js")),
      minify_runtime(&source),
    )
    .expect(&format!("failed to write {name}.min.js"));
  }

  // The ESM helpers, each on its own so that bundles can define only those they use. Optimized
  // apps' support private export names, and call them by short names. Libraries' keep theirs.
  let mut table = String::from(
    "// Generated by build.rs from the ESM helpers' sources (see `EsmHelpers`).\n\n\
     /// Each ESM helper optimized apps define, by its function's name, minified and renamed to its\n\
     /// name in the bundle.\n\
     pub(crate) const APP_ESM_HELPERS: &[(&str, &str)] = &[\n",
  );
  for (name, readable) in
    helper_functions(&read_sources(&["esm-helpers", "esm-export-all-private"]))
  {
    let minified = minify_runtime(&readable);
    table.push_str(&format!("  ({name:?}, r###\"{minified}\"###),\n"));
  }
  table.push_str(
    "];\n\n\
     /// Each ESM helper libraries define, by its function's name, as readable and minified code, which\n\
     /// keeps its name.\n\
     pub(crate) const LIBRARY_ESM_HELPERS: &[(&str, &str, &str)] = &[\n",
  );
  for (name, readable) in helper_functions(&read_sources(&["esm-helpers", "esm-export-all"])) {
    let minified = minify_keeping_names(&readable);
    table.push_str(&format!(
      "  ({name:?}, r###\"{readable}\"###, r###\"{minified}\"###),\n"
    ));
  }
  table.push_str("];\n");
  fs::write(out_dir.join("esm-helpers.rs"), table).expect("failed to write esm-helpers.rs");
}

fn read_sources(names: &[&str]) -> String {
  let mut source = String::new();
  for name in names {
    println!("cargo:rerun-if-changed=src/{name}.js");
    source.push_str(
      &fs::read_to_string(format!("src/{name}.js"))
        .expect(&format!("failed to read src/{name}.js")),
    );
  }
  source
}

/// Each function a source declares, by name, as readable code.
fn helper_functions(source: &str) -> Vec<(String, String)> {
  let source_map: Lrc<SourceMap> = Default::default();
  let source_file = source_map.new_source_file(
    FileName::Real("esm-helpers.js".into()).into(),
    source.to_string(),
  );
  let module = Parser::new(
    Syntax::Es(EsSyntax::default()),
    StringInput::from(&*source_file),
    None,
  )
  .parse_module()
  .expect("failed to parse the ESM helpers");
  module
    .body
    .into_iter()
    .filter_map(|item| match item {
      ModuleItem::Stmt(Stmt::Decl(Decl::Fn(declaration))) => Some(declaration),
      _ => None,
    })
    .map(|declaration| {
      let name = declaration.ident.sym.to_string();
      let program = Program::Module(Module {
        body: vec![ModuleItem::Stmt(Stmt::Decl(Decl::Fn(declaration)))],
        ..Default::default()
      });
      (name, emit(&program, source_map.clone(), false))
    })
    .collect()
}

/// Minifies a function, keeping its name.
fn minify_keeping_names(source: &str) -> String {
  let source_map: Lrc<SourceMap> = Default::default();
  let source_file = source_map.new_source_file(
    FileName::Real("helper.js".into()).into(),
    source.to_string(),
  );
  let globals = Globals::new();
  GLOBALS.set(&globals, || {
    let program = Parser::new(
      Syntax::Es(EsSyntax::default()),
      StringInput::from(&*source_file),
      None,
    )
    .parse_program()
    .expect("failed to parse an ESM helper");
    let unresolved_mark = Mark::new();
    let top_level_mark = Mark::new();
    let mut program = program;
    program.visit_mut_with(&mut resolver(unresolved_mark, top_level_mark, false));
    let mut program = optimize(
      program,
      source_map.clone(),
      None,
      None,
      &MinifyOptions {
        rename: true,
        compress: Some(CompressOptions::default()),
        mangle: Some(MangleOptions::default()),
        ..Default::default()
      },
      &ExtraOptions {
        unresolved_mark,
        top_level_mark,
        mangle_name_cache: None,
      },
    );
    program.visit_mut_with(&mut fixer(None));
    emit(&program, source_map.clone(), true)
  })
}

fn minify_runtime(source: &str) -> String {
  let source_map: Lrc<SourceMap> = Default::default();
  let source_file = source_map.new_source_file(
    FileName::Real("runtime.js".into()).into(),
    source.to_string(),
  );
  let comments = SingleThreadedComments::default();

  let globals = Globals::new();
  GLOBALS.set(&globals, || {
    let lexer = Lexer::new(
      Syntax::Es(EsSyntax::default()),
      EsVersion::Es2022,
      StringInput::from(&*source_file),
      Some(&comments),
    );

    let mut parser = Parser::new_from(lexer);
    let mut program = parser.parse_program().unwrap_or_else(|err| {
      HANDLER.with(|handler| err.into_diagnostic(handler).emit());
      panic!("failed to parse src/runtime.js");
    });

    for err in parser.take_errors() {
      HANDLER.with(|handler| err.into_diagnostic(handler).emit());
    }

    let unresolved_mark = Mark::new();
    let top_level_mark = Mark::new();
    program.visit_mut_with(&mut resolver(unresolved_mark, top_level_mark, false));
    // The minifier keeps a top-level name that is already reserved, which would then be declared
    // twice in the bundle (e.g. as both a variable and an ESM helper function).
    let mut declarations = TopLevelDeclarations {
      top_level_mark,
      names: Vec::new(),
    };
    program.visit_with(&mut declarations);
    for name in declarations.names {
      if RUNTIME_GLOBALS
        .iter()
        .any(|(_, minified)| *minified == name)
      {
        panic!("a runtime source declares the reserved top-level name `{name}`; rename it");
      }
    }
    program.visit_mut_with(&mut RuntimeAbiRenamer);

    let program = optimize(
      program,
      source_map.clone(),
      Some(&comments),
      None,
      &MinifyOptions {
        rename: true,
        compress: Some(CompressOptions::default()),
        mangle: Some(MangleOptions {
          top_level: Some(true),
          reserved: RUNTIME_GLOBALS
            .iter()
            .map(|(_, minified)| (*minified).into())
            .collect(),
          ..Default::default()
        }),
        ..Default::default()
      },
      &ExtraOptions {
        unresolved_mark,
        top_level_mark,
        mangle_name_cache: None,
      },
    );

    // The minifier's output relies on the fixer to parenthesize e.g. assignments within `&&`.
    let mut program = program;
    program.visit_mut_with(&mut fixer(Some(&comments)));
    emit_runtime(program, source_map)
  })
}

/// The names of the bindings a program declares at its top level.
struct TopLevelDeclarations {
  top_level_mark: Mark,
  names: Vec<String>,
}

impl Visit for TopLevelDeclarations {
  fn visit_binding_ident(&mut self, node: &swc_core::ecma::ast::BindingIdent) {
    self.visit_ident(&node.id);
  }

  fn visit_fn_decl(&mut self, node: &swc_core::ecma::ast::FnDecl) {
    self.visit_ident(&node.ident);
    node.function.visit_with(self);
  }

  fn visit_class_decl(&mut self, node: &swc_core::ecma::ast::ClassDecl) {
    self.visit_ident(&node.ident);
    node.class.visit_with(self);
  }

  fn visit_ident(&mut self, node: &swc_core::ecma::ast::Ident) {
    if node.ctxt.outer() == self.top_level_mark {
      self.names.push(node.sym.to_string());
    }
  }

  fn visit_expr(&mut self, node: &swc_core::ecma::ast::Expr) {
    // Only declarations, not references.
    if let swc_core::ecma::ast::Expr::Ident(_) = node {
      return;
    }
    node.visit_children_with(self);
  }
}

struct RuntimeAbiRenamer;

impl VisitMut for RuntimeAbiRenamer {
  fn visit_mut_ident(&mut self, node: &mut swc_core::ecma::ast::Ident) {
    for (readable, minified) in RUNTIME_GLOBALS {
      if node.sym == *readable {
        node.sym = (*minified).into();
        break;
      }
    }
  }
}

fn emit_runtime(program: Program, source_map: Lrc<SourceMap>) -> String {
  emit(&program, source_map, true)
}

fn emit(program: &Program, source_map: Lrc<SourceMap>, minify: bool) -> String {
  let mut buf = Vec::new();
  {
    let writer: Box<dyn WriteJs> = if minify {
      Box::new(omit_trailing_semi(JsWriter::new(
        source_map.clone(),
        "\n",
        &mut buf,
        None,
      )))
    } else {
      Box::new(JsWriter::new(source_map.clone(), "\n", &mut buf, None))
    };
    let mut emitter = Emitter {
      cfg: Config::default()
        .with_target(EsVersion::Es5)
        .with_ascii_only(true)
        .with_minify(minify)
        .with_omit_last_semi(minify),
      comments: None,
      cm: source_map.clone(),
      wr: writer,
    };

    emitter.emit_program(program).expect("failed to emit");
  }

  String::from_utf8(buf).expect("emitted code is not valid utf-8")
}
